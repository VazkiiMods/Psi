	@SafeVarargs
	private static void group(BootstrapContext<SpellPieceGroup> context, String name,
			RegistryEntry<SpellPieceType> main, RegistryEntry<SpellPieceType>... pieces) {
		context.register(ResourceKey.create(PsiAPI.SPELL_PIECE_GROUP_REGISTRY_KEY, PsiAPI.location(name)),
				new SpellPieceGroup(main.id(), Arrays.stream(pieces).map(RegistryEntry::id).toList()));
	}

